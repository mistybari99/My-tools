#!/usr/bin/env python3
"""Parse audit2 suite outputs and write docs/audit2/VERIFY_STATUS.md.
usage: verify_report.py <out.md> <gap_map.tsv> <info.json> <label>=<dir> [<label>=<dir>]
<dir> holds a1.txt..a5.txt (raw psql output).  Statuses per gap: PASS / FAIL / NOT SUPPORTED / NO PROBE."""
import sys, re, json, os, datetime
out, gmap, info = sys.argv[1], sys.argv[2], json.load(open(sys.argv[3]))
passes = [a.split("=", 1) for a in sys.argv[4:]]
LINE = re.compile(r"(?:^|\s)(PASS|FAIL) (.*)$")

def parse(d):
    res = {}
    for n in range(1, 6):
        p = os.path.join(d, f"a{n}.txt"); L = []
        if os.path.exists(p):
            for ln in open(p, errors="replace"):
                ln = ln.rstrip("\n")
                if "NOTICE:" in ln: ln = ln.split("NOTICE:", 1)[1].strip()
                m = re.match(r"(PASS|FAIL) (.*)$", ln)
                if not m: continue
                full = m.group(2); label = full.split(" exp=")[0]
                L.append((m.group(1) == "PASS", label, full))
        res[f"A{n}"] = L
    return res

gaps = {}  # id -> {title, rules[(kind, re)]}
order = []
for ln in open(gmap):
    if ln.startswith("#") or not ln.strip(): continue
    gid, kind, rx, title = ln.rstrip("\n").split("\t")
    if gid not in gaps: gaps[gid] = {"title": title, "rules": []}; order.append(gid)
    if kind != "-": gaps[gid]["rules"].append((kind, re.compile(rx)))

def status(gid, probes):
    rules = gaps[gid]["rules"]
    if not rules: return "NO PROBE", [], 0
    suite = gid.split("-")[0]; P = probes[suite]; hits = []; open_ = False; ns = False; seen = 0
    for kind, rx in rules:
        for ok, label, full in P:
            if not rx.search(label): continue
            seen += 1
            bad = (not ok) if kind in "AN" else ok
            if bad:
                hits.append(("FAIL" if not ok else "PASS") + " " + label[:90] + (" [pin: still old behaviour]" if kind == "P" else ""))
                if kind == "N": ns = True
                else: open_ = True
    if seen == 0: return "NO PROBE", ["(probe labels not found in output - suite did not run or labels changed)"], 0
    if ns and not open_: return "NOT SUPPORTED", hits, seen
    if ns or open_: return "FAIL", hits, seen
    return "PASS", [], seen

R = []
for label, d in passes:
    pr = parse(d); st = {g: status(g, pr) for g in order}
    mapped = [(rx, k) for g in order for k, rx in gaps[g]["rules"]]
    unm = []
    for s, L in pr.items():
        for ok, lab, full in L:
            if not ok and not any(rx.search(lab) and s == g.split("-")[0] for g in order for k, rx in gaps[g]["rules"]):
                unm.append(f"{s}: {lab[:100]}")
    R.append((label, pr, st, unm))

def counts(st):
    c = {"PASS": 0, "FAIL": 0, "NOT SUPPORTED": 0, "NO PROBE": 0}
    for v in st.values(): c[v[0]] += 1
    return c

W = []; w = W.append
w("# Audit 2 - verification status (machine generated)\n")
w("Generated by `tests/sql/audit2/run_all.sh` on " + datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC") + f" - base commit `{info.get('commit','?')}`. Do not edit by hand; re-run the script.\n")
w("How to read: **PASS** = every probe for the gap shows the correct behaviour (gap closed); **FAIL** = at least one probe still shows the gap; **NOT SUPPORTED** = the feature does not exist yet; **NO PROBE** = the gap is documented/code-read only (no machine probe yet - add one in the suite and a row in `gap_map.tsv`). Probe kinds: `assert` probes check the correct behaviour; `pin` probes pin today's behaviour (a pin that PASSES means the old behaviour is still there).\n")
w("## Summary\n")
w("| Pass | Suite probes (PASS/FAIL) | Gaps PASS | Gaps FAIL | Gaps NOT SUPPORTED | Gaps NO PROBE |")
w("|---|---|---|---|---|---|")
for label, pr, st, unm in R:
    c = counts(st); tp = sum(1 for L in pr.values() for x in L if x[0]); tf = sum(1 for L in pr.values() for x in L if not x[0])
    w(f"| {label} | {tp} / {tf} | {c['PASS']} | {c['FAIL']} | {c['NOT SUPPORTED']} | {c['NO PROBE']} |")
w("")
w("Per suite probes (PASS/FAIL): " + "; ".join(f"{label}: " + ", ".join(f"{s} {sum(1 for x in L if x[0])}/{sum(1 for x in L if not x[0])}" for s, L in pr.items()) for label, pr, st, unm in R) + "\n")
if info.get("new_rules"):
    w("## New rules found in the built DB (not in rules_baseline.txt)\n")
    w("| Rule | Kind | Default | Switched ON in the switches pass |"); w("|---|---|---|---|")
    for r in info["new_rules"]: w(f"| `{r['key']}` | {r['kind']} | {r['default']} | {r['on']} |")
    w("")
else:
    w("## New rules\n\nNone yet (rule table equals rules_baseline.txt). Phases 112-118 not in the build: " + (", ".join(info.get("missing_phases", [])) or "n/a") + ".\n")
if info.get("switch_notes"): w("Switch pass notes: " + "; ".join(info["switch_notes"]) + "\n")
w("## Gap status\n")
hdr = "| Gap | Title | " + " | ".join(l for l, *_ in R) + " | Probes |"
w(hdr); w("|---|---|" + "---|" * len(R) + "---|")
sev = {"PASS": "PASS", "FAIL": "**FAIL**", "NOT SUPPORTED": "**NOT SUPPORTED**", "NO PROBE": "no probe"}
for g in order:
    cells = [sev[st[g][0]] for _, _, st, _ in R]
    n = R[0][2][g][2]
    basis = "/".join(sorted({"assert" if k in "AN" else "pin" for k, _ in gaps[g]["rules"]})) or "-"
    w(f"| {g} | {gaps[g]['title']} | " + " | ".join(cells) + f" | {basis} ({n}) |")
w("")
for label, pr, st, unm in R:
    w(f"## Open probes - pass `{label}`\n")
    for g in order:
        if st[g][0] in ("FAIL", "NOT SUPPORTED"):
            w(f"- **{g}** ({st[g][0]}): " + "; ".join(st[g][1][:6]))
    w("")
    w(f"FAIL probes not mapped to any gap in gap_map.tsv ({len(unm)}):" + (" none" if not unm else ""))
    for u in unm: w(f"- {u}")
    w("")
if len(R) > 1:
    a, b = R[0], R[1]
    ch = [g for g in order if a[2][g][0] != b[2][g][0]]
    w("## Switch matrix: gaps whose status changes when the recommended switches are ON\n")
    if not ch: w("None.\n")
    for g in ch: w(f"- {g}: {a[2][g][0]} -> {b[2][g][0]} ({gaps[g]['title']})")
    w("")
w("## Re-run\n\n```\nbash tests/sql/audit2/run_all.sh --matrix      # build b5run, run a1..a5 at defaults and with switches ON, rewrite this file\nbash tests/sql/audit2/run_all.sh --no-build     # re-use the existing b5run DB, defaults only\n```\n")
open(out, "w").write("\n".join(W))
print("wrote", out); 
for label, pr, st, unm in R: print(label, counts(st), "unmapped FAIL:", len(unm))
