#!/usr/bin/env python3
"""Generate docs/audit_rpt/REPORT_MATRIX.md from tools/rpt_matrix_rows.txt (run from the repo root). Evidence file:line is resolved from the canonical phase order,
and the verification column is filled from a search of the SQL test files, so the matrix cannot claim a test that does not exist."""
import re, glob, os, json, collections
env=open('tests/sql/paste_order.env').read(); order=[]
for k in ('FOUNDATION','NEW'): order+=re.search(k+'="([^"]*)"',env).group(1).split()
fn={}; tbl={}; keyloc={}
pat=re.compile(r'create\s+(?:or\s+replace\s+)?function\s+(?:public\.)?"?([a-z0-9_]+)"?\s*\(',re.I)
tpat=re.compile(r'create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?"?([a-z0-9_]+)"?',re.I)
for ph in order:
    try: lines=open(f'supabase/{ph}.sql',encoding='utf8',errors='ignore').read().split('\n')
    except: continue
    for i,l in enumerate(lines,1):
        m=pat.search(l)
        if m: fn[m.group(1).lower()]=f'supabase/{ph}.sql:{i}'
        m=tpat.search(l)
        if m: tbl.setdefault(m.group(1).lower(),f'supabase/{ph}.sql:{i}')
        for k in re.findall(r'"([a-z][a-z0-9_]+)":\s*\{"group"',l): keyloc[k]=f'supabase/{ph}.sql:{i}'
        for k in re.findall(r"p_key\s*=\s*'([a-z0-9_]+)'",l): keyloc.setdefault(k,f'supabase/{ph}.sql:{i}')
        if ph=='phase24':
            for k in re.findall(r"\('([a-z][0-9]_[a-z_0-9]+)'",l): keyloc.setdefault(k,f'supabase/{ph}.sql:{i}')
        # engine 1 definitions "name":{"group"... inside rpt_def
for f in sorted(glob.glob('supabase/*.sql')):
    if f.endswith('_test.sql'): continue
    for i,l in enumerate(open(f,encoding='utf8',errors='ignore').read().split('\n'),1):
        m=pat.search(l)
        if m and m.group(1).lower() not in fn: fn[m.group(1).lower()]=f+':'+str(i)
tests=[]
for f in glob.glob('supabase/*_test.sql')+glob.glob('tests/sql/**/*.sql',recursive=True): tests.append((f,open(f,encoding='utf8',errors='ignore').read()))
def tested(tok):
    hits=[os.path.basename(f) for f,t in tests if re.search(r'\b'+re.escape(tok)+r'\b',t)]
    return hits
def resolve(tok):
    tok=tok.strip()
    if tok.startswith('S1:'):
        n=tok[3:]; return fn.get(n.lower()), n, ['phase131_test.sql'] if n.startswith(('rpt131','_rpt131')) else tested(n)
    if tok.startswith('web:'):
        f='web/'+tok[4:]; return (f+':1' if os.path.exists(f) else None), tok[4:], ['tests/web (mocked RPCs)'] if os.path.exists(f) else []
    if tok.startswith('key:'):
        k=tok[4:]; return (fn.get('_r3q_'+k) or keyloc.get(k)), 'report '+k, tested(k)+tested('_r3q_'+k)
    n=tok.lower()
    if n in fn: return fn[n], tok, tested(tok)
    if n in tbl: return tbl[n]+' (table)', tok, []
    if tok in ('-',''): return 'skip', tok, []
    return 'rule/column/account (no function)', tok, []
rows=[l.split('|') for l in open('tools/rpt_matrix_rows.txt',encoding='utf8').read().strip().split('\n')]
G=['','Executive dashboard','Sales & POS','Product profitability & pricing','Production / recipe / BOM','Raw materials & inventory','Freshness / wastage / food safety','Purchasing / suppliers','Cash / banking / financial','Customers & credit','Staff / attendance / payroll','Orders / cake orders / delivery','Marketing / promotions','Audit / compliance','Planning / forecasting','Required report behaviour','Final verification']
EX={'W':'existing-working','R':'needs repair','M':'missing','N':'needs new data capture'}
out=[]; cnt=collections.Counter(); cnt2=collections.Counter(); cross=collections.Counter()
out.append("# REPORT MATRIX - sweets business reporting requirements (193 items, 16 groups)\n")
out.append("Generated by `tools/rpt_matrix_gen.py` from `tools/rpt_matrix_rows.txt` (re-run after changes). Evidence `file:line` is the LAST definition in the canonical paste order; the verification column is a search of `supabase/*_test.sql` and `tests/sql/**` for the function or report key - a report with no hit is marked unverified, whatever its menu entry says.\n")
out.append("**Where the 193 items come from.** The owner's verbatim list is not in the repository. The 193 items below are a reconstruction from the 16 group names, `docs/plan_v2/REPORTS.md` (65 catalogue reports), the 62 reports/statements now in the engines and the audits A1-A5. Each item is one report, screen behaviour or check the owner asked for. If the owner's list differs, change `tools/rpt_matrix_rows.txt` and re-run the generator.\n")
out.append("Status words. **Existing status** (before Stage 1): existing-working / needs repair / missing / needs new data capture. **Implementation status** (after Stage 1, honest): implemented = code + an automated test that checks numbers; incomplete = works for part of the job (switch OFF by default, partly unscoped, not net of returns, no drill, ...); unverified = code exists but no automated test with numbers was found or it reads typed paper-form jsonb; unavailable = nothing usable (missing, or the data is not captured). A menu item alone is never counted as implemented.\n")
cur=0
EFF={}
for idx,r in enumerate(rows):
    g=int(r[0]); name,st,impl,ev,src,logic,dep=r[1:8]
    vs=set()
    for tok in ev.split(','):
        vs.update(resolve(tok)[2])
    if impl=='implemented' and not vs: impl='unverified'; r.append('downgraded')
    EFF[idx]=impl
    cnt[(g,st)]+=1; cnt2[impl]+=1; cross[(st,impl)]+=1
body=[]
for g in range(1,17):
    body.append(f"\n## {g}. {G[g]}\n")
    body.append("| # | Report | Existing status | Implementation status | Data source | Calculation logic | Verification result | Outstanding dependencies | Evidence (file:line, function) |")
    body.append("|---|---|---|---|---|---|---|---|---|")
    n=0
    for idx,r in enumerate(rows):
        if int(r[0])!=g: continue
        n+=1; name,st,impl,ev,src,logic,dep=r[1:8]; impl=EFF[idx]
        evs=[]; vs=set(); anyfound=False
        for tok in ev.split(','):
            loc,label,t=resolve(tok)
            if loc=='skip': continue
            if loc: evs.append(f"`{label}` {loc}"); anyfound=True
            else: evs.append(f"`{label}` (no definition found)" if tok else '')
            vs.update(t)
        vs=sorted(vs)
        impl_note=' (downgraded: no automated test found)' if len(r)>8 and r[8]=='downgraded' else ''
        ver=("tested in: "+', '.join(vs[:4])+(f" (+{len(vs)-4})" if len(vs)>4 else '')) if vs else ("no automated test found" )
        if 'S1:' in ev and any(x.startswith('phase131') for x in vs): ver="phase131_test.sql (hand-computed numbers)"+ (", also "+', '.join([v for v in vs if not v.startswith('phase131')][:3]) if len([v for v in vs if not v.startswith('phase131')]) else '')
        body.append(f"| {g}.{n:02d} | {name} | {EX[st]} | {impl}{impl_note} | {src} | {logic} | {ver} | {dep} | {'; '.join(e for e in evs if e)} |")
out+= body
# summary
sumlines=["## Counts\n","| Group | existing-working | needs repair | missing | needs new data capture | total |","|---|---|---|---|---|---|"]
tot=collections.Counter()
for g in range(1,17):
    c=[cnt[(g,s)] for s in 'WRMN']; tot.update(dict(zip('WRMN',c)))
    sumlines.append(f"| {g}. {G[g]} | {c[0]} | {c[1]} | {c[2]} | {c[3]} | {sum(c)} |")
sumlines.append(f"| **Total** | **{tot['W']}** | **{tot['R']}** | **{tot['M']}** | **{tot['N']}** | **{sum(tot.values())}** |\n")
sumlines.append("| Implementation status after Stage 1 | items |\n|---|---|")
for k in ('implemented','incomplete','unverified','unavailable'): sumlines.append(f"| {k} | {cnt2[k]} |")
sumlines.append(f"| **Total** | **{sum(cnt2.values())}** |\n")
sumlines.append("Cross table (existing status -> implementation status):\n\n| existing \\ now | implemented | incomplete | unverified | unavailable |\n|---|---|---|---|---|")
for s in 'WRMN': sumlines.append(f"| {EX[s]} | "+" | ".join(str(cross[(s,k)]) for k in ('implemented','incomplete','unverified','unavailable'))+" |")
sumlines.append("")
out=out[:4]+sumlines+out[4:]
open('docs/audit_rpt/REPORT_MATRIX.md','w',encoding='utf8').write('\n'.join(out)+'\n')
print(dict(tot), dict(cnt2))
