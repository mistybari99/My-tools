#!/usr/bin/env python3
"""Package the public storefront (site/) for ANY static host. No network, no build tools.

What it does
  1. Reads the PUBLIC values from web/config.js (Supabase project URL + publishable key) and REFUSES any secret key
     (sb_secret_..., a JWT whose role is service_role). The shop name and settings are NOT here: the site reads them at run time
     from the public RPC web_site_config (set in the ERP Website screen).
  2. Writes site/config.js (the only file that differs between a test copy and a live copy).
  3. Lints every file under site/: no secret words, no private key, and only the allowed external hosts.
  4. With --out DIR: copies site/ to DIR and writes robots.txt and sitemap.xml (needs --base-url, the final https address).
     With --zip: also writes DIR.zip next to it, ready to upload to Netlify, Cloudflare Pages, GitHub Pages or a bucket.

Usage
  python3 tools/build_site.py --check                       # validate config + lint only (exit 1 on a problem)
  python3 tools/build_site.py --out dist/site --base-url https://example.com --zip
  python3 tools/build_site.py --out dist/site               # no base url: no sitemap, a warning is printed
Deploy guides: docs/WEBSITE_DEPLOY.md.
"""
import base64
import datetime
import json
import os
import re
import shutil
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'site')
CFG_SRC = os.path.join(ROOT, 'web', 'config.js')
ALLOWED_HOSTS = {
    'schema.org', 'www.w3.org', 'connect.facebook.net', 'www.googletagmanager.com', 'wa.me',
}
SECRET_WORDS = [r'service_role', r'sb_secret_', r'SERVICE_ROLE', r'BEGIN (RSA |EC )?PRIVATE KEY', r'SUPABASE_SERVICE', r'eyJhbGciOi[^"\']{0,40}service']
PAGES = ['index.html', 'catalogue.html', 'product.html', 'cart.html', 'checkout.html', 'confirm.html', 'track.html',
         'custom-cake.html', 'contact.html', 'policies.html']


def fail(msg):
    print('FAIL ' + msg)
    return False


def jwt_role(token):
    """Return the 'role' claim of a JWT, or None (never raises)."""
    try:
        part = token.split('.')[1]
        part += '=' * (-len(part) % 4)
        return json.loads(base64.urlsafe_b64decode(part.encode('ascii'))).get('role')
    except Exception:
        return None


def read_public_config(path=CFG_SRC):
    if not os.path.exists(path):
        return None, 'web/config.js not found'
    txt = open(path, encoding='utf-8').read()
    url = re.search(r'url:\s*"([^"]+)"', txt)
    key = re.search(r'key:\s*"([^"]+)"', txt)
    if not url or not key:
        return None, 'web/config.js has no url/key'
    return {'url': url.group(1).rstrip('/'), 'key': key.group(1)}, None


def check_config(cfg):
    ok = True
    if not re.match(r'^https://[a-z0-9]{10,30}\.supabase\.co$', cfg['url']) and not re.match(r'^http://(localhost|127\.0\.0\.1)(:\d+)?$', cfg['url']):
        ok = fail('the Supabase URL must be https://<project>.supabase.co (got %s)' % cfg['url'])
    k = cfg['key']
    if k.startswith('sb_secret_'):
        ok = fail('a SECRET key was found in web/config.js; only the publishable key may be used here')
    if k.count('.') == 2 and jwt_role(k) == 'service_role':
        ok = fail('a service_role key was found; only the publishable/anon key may be used here')
    if not (k.startswith('sb_publishable_') or k.startswith('eyJ')):
        ok = fail('the key is neither a publishable key (sb_publishable_...) nor an anon JWT')
    return ok


def lint(root):
    ok = True
    files = []
    for d, _, fs in os.walk(root):
        for f in fs:
            if f.endswith(('.html', '.js', '.css', '.json', '.webmanifest', '.svg', '.txt', '.xml')):
                files.append(os.path.join(d, f))
    if not files:
        return fail('no site files found in ' + root)
    for path in files:
        rel = os.path.relpath(path, root)
        txt = open(path, encoding='utf-8', errors='replace').read()
        for pat in SECRET_WORDS:
            if re.search(pat, txt):
                ok = fail('%s contains a forbidden secret pattern (%s)' % (rel, pat))
        for host in re.findall(r'https?://([A-Za-z0-9.\-]+)', txt):
            if host in ALLOWED_HOSTS or host.endswith('.supabase.co') or host in ('localhost', '127.0.0.1'):
                continue
            ok = fail('%s calls an unexpected external host: %s' % (rel, host))
    return ok


def write_config(cfg, root):
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    body = ('// GENERATED by tools/build_site.py from web/config.js (public values only). Do not put secrets here.\n'
            'window.SITE_CONFIG = {\n'
            '  url: %s,\n  key: %s,\n  built: %s\n};\n') % (json.dumps(cfg['url']), json.dumps(cfg['key']), json.dumps(stamp))
    with open(os.path.join(root, 'config.js'), 'w', encoding='utf-8') as f:
        f.write(body)


def sitemap(base, with_custom):
    pages = ['index.html', 'catalogue.html', 'contact.html', 'policies.html', 'track.html']
    if with_custom:
        pages.append('custom-cake.html')
    urls = ''.join('  <url><loc>%s/%s</loc></url>\n' % (base, p if p != 'index.html' else '') for p in pages)
    return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n%s</urlset>\n' % urls


def main(argv):
    args = {'check': '--check' in argv, 'zip': '--zip' in argv, 'out': None, 'base': None}
    for i, a in enumerate(argv):
        if a == '--out' and i + 1 < len(argv):
            args['out'] = argv[i + 1]
        if a == '--base-url' and i + 1 < len(argv):
            args['base'] = argv[i + 1].rstrip('/')
    cfg, err = read_public_config()
    if err:
        print('FAIL ' + err)
        return 1
    ok = check_config(cfg)
    if args['base'] and not re.match(r'^https://[A-Za-z0-9.\-]+(:\d+)?(/[A-Za-z0-9._~/-]*)?$', args['base']):
        ok = fail('--base-url must be an https:// address (got %s)' % args['base'])
    write_config(cfg, SITE)
    ok = lint(SITE) and ok
    if not ok:
        return 1
    print('OK site/ checked: config valid, no secret, external hosts allowed')
    if args['check'] or not args['out']:
        return 0
    out = os.path.abspath(args['out'])
    if os.path.exists(out):
        shutil.rmtree(out)
    shutil.copytree(SITE, out)
    if args['base']:
        with open(os.path.join(out, 'robots.txt'), 'w', encoding='utf-8') as f:
            f.write('User-agent: *\nAllow: /\nSitemap: %s/sitemap.xml\n' % args['base'])
        with open(os.path.join(out, 'sitemap.xml'), 'w', encoding='utf-8') as f:
            f.write(sitemap(args['base'], True))
    else:
        print('WARN no --base-url: robots.txt and sitemap.xml were not written (the sitemap needs the final https address)')
    print('OK packaged to ' + out + ' (%d files)' % sum(len(fs) for _, _, fs in os.walk(out)))
    if args['zip']:
        zp = out + '.zip'
        with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
            for d, _, fs in os.walk(out):
                for f in fs:
                    full = os.path.join(d, f)
                    z.write(full, os.path.relpath(full, out))
        print('OK zip ' + zp)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
