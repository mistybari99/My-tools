#!/usr/bin/env python3
"""Compare the paper Form Kit (docs/inputs/BOS-BUILD-KIT_All_Forms_v1_39.js) with the app form specs (web/forms*.js).
Read-only. Writes docs/KIT_MATCH.md. It is a SUSPECT LIST for a human to review, not a verdict:
  - "paper only"  = a short printed label on the paper form that the app spec does not contain in any language (maybe a missing field, maybe a wording change)
  - "app only"    = an app label that the paper form does not contain (maybe an invented field, maybe a new help text)
Matching is on normalised text (punctuation, digits, spacing, the printed tick/underline marks removed)."""
import re, sys, json, glob, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIT = os.path.join(ROOT, 'docs/inputs/BOS-BUILD-KIT_All_Forms_v1_39.js')
OUT = os.path.join(ROOT, 'docs/KIT_MATCH.md')

def norm(s):
    s = s.lower()
    s = re.sub(r'[☐☑●■□_:;,.·()\[\]{}"\'`/\\|*+=<>?!#%&~^-]|[0-9০-৯]', ' ', s)   # marks, punctuation, digits
    s = re.sub(r'[‌‍]', '', s)
    return re.sub(r'\s+', ' ', s).strip()

STR = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'|`((?:[^`\\]|\\.)*)`')
def literals(text):
    for m in STR.finditer(text):
        yield next(g for g in m.groups() if g is not None)

# ---------- Kit: split into functions, find the form code of each ----------
kit = open(KIT, encoding='utf-8').read()
HELPERS = {'cell', 'head', 'build', 'section', 'cutLine', 'LN_HEAD', 'LN_NUM', 'scale', 'bar', 'foot', 'legend', 'gap', 'run', 'para', 'table', 'hdr', 'row', 'tall', 'span', 'M'}
funcs = []                                                    # (name, body)
for m in re.finditer(r'^function (\w+)\(', kit, re.M):
    funcs.append((m.group(1), m.start()))
bodies = []
for i, (name, st) in enumerate(funcs):
    en = funcs[i + 1][1] if i + 1 < len(funcs) else len(kit)
    bodies.append((name, kit[st:en]))
forms = {}                                                    # code -> text of all its functions
for name, body in bodies:
    if name in HELPERS or name.startswith('LN_'):
        continue
    codes = re.findall(r'ফরম\s+(\d{1,2}-\d{1,2})\b', body) + re.findall(r'\bhead\(\s*"[^"]*"\s*,\s*"[^"]*"\s*,\s*"(\d{1,2}-\d{1,2})"', body) + re.findall(r'\b(\d{1,2}-\d{1,2})\s*·', body)
    if not codes:
        continue
    code = max(set(codes), key=codes.count)
    forms.setdefault(code, []).append(body)
# the group comments carry the form number in a few cases: ফরম footers are the reliable key, so forms with no footer are listed as unmatched below

# ---------- App: forms*.js blocks ----------
app = {}
app_ctx = {}
for fn in sorted(glob.glob(os.path.join(ROOT, 'web/forms*.js'))):
    t = open(fn, encoding='utf-8').read()
    idx = [(m.group(1), m.start()) for m in re.finditer(r"B\.forms\['([0-9]+-[0-9]+)'\]\s*=", t)]
    for i, (code, st) in enumerate(idx):
        en = idx[i + 1][1] if i + 1 < len(idx) else len(t)
        app.setdefault(code, '')
        app[code] += t[st:en]
        app_ctx[code] = app_ctx.get(code, '') + t[max(0, st - 2500):en]       # + the shared constants (heads lists, units) declared just before the form; used only for 'is it covered'

def app_labels(block):
    out = []
    for m in re.finditer(r"L\(\s*(?:'((?:[^'\\]|\\.)*)'|\"((?:[^\"\\]|\\.)*)\")\s*,\s*(?:'((?:[^'\\]|\\.)*)'|\"((?:[^\"\\]|\\.)*)\")", block):
        bn = m.group(1) or m.group(2) or ''
        en = m.group(3) or m.group(4) or ''
        out.append((bn, en))
    return out

def words(n):
    return {w for w in n.split() if len(w) >= 2}

def covered(n, other_norm, other_words):
    if n in other_norm:
        return True
    w = words(n)
    return bool(w) and len(w & other_words) / len(w) >= 0.8

SKIP = re.compile(r'^(?:[A-Za-z]+(?:[A-Z][a-z]+)+|[0-9A-Fa-f]{6}|Noto Sans Bengali|docx|fs|atLeast|center|left|right|top|bottom|dxa)$')
GENERIC = {'তারিখ', 'ক্র নং', 'নং', 'লোকেশন'}      # the form frame (date, serial, place) is drawn by the app engine, not by each spec
BOILER = {'ইসলামিয়া মিষ্টি ঘর', 'চিত্রালী বিআইডিসি রোড খালিশপুর খুলনা since', 'বাধ্যতামূলক ঘর'}

def kit_labels(texts):
    seen, out = set(), []
    for body in texts:
        for s in literals(body):
            if re.search(r'^[A-Za-z0-9_./-]+\.docx$', s) or len(s) > 70:
                continue
            n = norm(s)
            if len(n) < 3 or not re.search(r'[a-zঀ-৿]', n) or n in seen:
                continue
            seen.add(n); out.append((s.strip(), n))
    return out

codes = sorted(set(forms) | set(app), key=lambda c: (int(c.split('-')[0]), int(c.split('-')[1])))
lines = ['# Form Kit v1.39 vs app form specs - suspect list', '',
         '_Generated by `tools/kit_match.py` (read-only). This is a text match, not a meaning match: every line needs a human look._', '',
         '- **paper only** = a short printed label of the paper form that no app label contains (missing field, or just a wording change).',
         '- **app only** = an app label the paper form does not contain (new field, help text, or a wording change).',
         '- Digits, ticks, underlines, punctuation are ignored. Labels longer than 70 characters (rules/notes) are not compared.',
         '- Many "paper only" lines are print-only text (copy routing like `এক কপি: হাব`, press notes, signature captions) that the app engine does not repeat as fields.',
         '- Form 0-1 (location settings) is not a form spec in the app: it is the location settings screens (`locset` / `locsheet`).', '']
summary = []
for code in codes:
    kt = kit_labels(forms.get(code, []))
    al = app_labels(app.get(code, ''))
    kit_norm = ' '.join(n for _, n in kt)
    app_norm_all = norm(' '.join(b + ' ' + e for b, e in al) + ' ' + ' '.join(literals(app_ctx.get(code, ''))))
    app_words = words(app_norm_all)
    paper_only = [s for s, n in kt if len(n) <= 50 and not covered(n, app_norm_all, app_words)]
    kit_words = words(kit_norm)
    app_only = []
    for bn, en in al:
        nb = norm(bn)
        if len(nb) < 3 or len(bn) > 70:
            continue
        if not covered(nb, kit_norm, kit_words):
            app_only.append(bn.strip())
    status = 'NO KIT FUNCTION FOUND' if not kt else ('NO APP SPEC FOUND' if not al else '')
    summary.append((code, len(kt), len(al), len(paper_only), len(app_only), status))
    lines += [f'## {code}', f'- paper labels: {len(kt)} · app labels: {len(al)} · paper only: {len(paper_only)} · app only: {len(app_only)}' + (f' · **{status}**' if status else '')]
    if paper_only:
        lines += ['- paper only: ' + ' · '.join(f'`{x}`' for x in paper_only[:40]) + (f' … (+{len(paper_only)-40})' if len(paper_only) > 40 else '')]
    if app_only:
        lines += ['- app only: ' + ' · '.join(f'`{x}`' for x in app_only[:40]) + (f' … (+{len(app_only)-40})' if len(app_only) > 40 else '')]
    lines.append('')
head = ['| form | paper labels | app labels | paper only | app only | note |', '|---|---|---|---|---|---|']
head += [f'| {c} | {a} | {b} | {d} | {e} | {s} |' for c, a, b, d, e, s in summary]
i = lines.index('')  # first blank after title block
lines[lines.index('## ' + codes[0]):lines.index('## ' + codes[0])] = head + ['']
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('forms in kit:', len([c for c in codes if c in forms]), 'forms in app:', len([c for c in codes if c in app]), '->', OUT)
tot_p = sum(x[3] for x in summary); tot_a = sum(x[4] for x in summary)
print('paper-only labels:', tot_p, 'app-only labels:', tot_a)
