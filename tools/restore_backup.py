#!/usr/bin/env python3
"""Turn a backup folder (made by tools/backup_dump.py) into SQL files that the OWNER pastes into the Supabase SQL editor. No database access is needed here.

    python3 tools/restore_backup.py <backup_folder> [--out restore.sql] [--dry-run] [--tables a,b] [--truncate] [--split-mb 4] [--chunk-rows 300]

* Verifies every table file against manifest.json (sha256 and row count) first. A damaged backup is refused.
* --dry-run prints the table list with row counts and writes NOTHING.
* Writes restore.sql (or restore.part01.sql, part02 ... when --split-mb is exceeded; paste them in order). Each file is one transaction.
* How the SQL works: it sets session_replication_role = replica (so foreign keys, the audit trail and the "nothing is deleted" triggers do not fire during the
  restore), then for every table inserts the rows with jsonb_populate_recordset (columns that the database generates itself, such as totals, are left to the database),
  and finally moves every serial sequence past the highest restored id.
* Default mode adds only rows that are missing (ON CONFLICT DO NOTHING): existing rows are never changed. --truncate empties ALL the restored tables first, in one
  statement at the start (DESTRUCTIVE - for restoring into a new copy of the app whose phase SQL was just run; the append-only / no-delete guards are switched off
  for that moment and put back as they were; the output says so in its first lines).
* Order: tables are restored alphabetically; foreign keys are not checked because of session_replication_role = replica. The auth users (logins) are NOT in the
  backup: restore into the SAME Supabase project, or re-create the users with the same ids first (profiles.id points at auth.users.id).
* The photos live in Storage and are not in this SQL (see docs/OPS_SETUP.md, tools/backup_photos.py).
"""
import argparse
import gzip
import hashlib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ops_common as oc  # noqa: E402

HEAD = ('-- Restore generated by tools/restore_backup.py from a backup made at {finished}.\n-- Mode: {mode}.\n'
        '-- Run in the Supabase SQL editor as the project owner. {warn}\nbegin;\nset local session_replication_role = replica;\n')
WARN_TRUNC = 'WARNING: --truncate mode: every table listed below is EMPTIED first. Use only on a new empty copy.'
SAFE_NAME = re.compile(r'^[a-z_][a-z0-9_]{0,62}$')


def load_manifest(folder):
    with open(os.path.join(folder, 'manifest.json'), encoding='utf-8') as f:
        return json.load(f)


def read_rows(path):
    with gzip.open(path, 'rt', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line:
                yield oc.loads_exact(line)


def verify(folder, manifest, names):
    """Returns the list of problems (empty = the backup is intact)."""
    bad = []
    for t in names:
        info = manifest['tables'].get(t)
        if info is None:
            bad.append(f'{t}: not in the manifest')
            continue
        p = os.path.join(folder, info['file'])
        if not os.path.isfile(p):
            bad.append(f'{t}: file missing')
            continue
        with open(p, 'rb') as f:
            data = f.read()
        if hashlib.sha256(data).hexdigest() != info['sha256']:
            bad.append(f'{t}: sha256 does not match (file damaged)')
            continue
        n = sum(1 for _ in read_rows(p))
        if n != info['rows']:
            bad.append(f'{t}: {n} rows in the file but the manifest says {info["rows"]}')
    return bad


def pick_tag(text, stem='bk'):
    i = 0
    while True:
        tag = '$%s%d$' % (stem, i)
        if tag not in text:
            return tag
        i += 1


def truncate_sql(names):
    """ONE block that empties every table to be restored (before any insert, so a CASCADE can never wipe a table that was restored earlier).
    The user triggers of each table (append-only / no-delete guards) are switched off for that moment and put back exactly as they were."""
    for t in names:
        if not SAFE_NAME.match(t):
            raise SystemExit(f'refusing an unsafe table name: {t!r}')
    arr = ', '.join("'" + t + "'" for t in names)
    tl = ', '.join('public.' + t for t in names)
    return (
        "do $r$ declare t text; tr record; x jsonb; saved jsonb := '[]'::jsonb; begin\n"
        f"  foreach t in array array[{arr}] loop\n"
        "    for tr in select tgname, tgenabled from pg_trigger where tgrelid = ('public.' || quote_ident(t))::regclass and not tgisinternal loop\n"
        "      saved := saved || jsonb_build_array(jsonb_build_array(t, tr.tgname, tr.tgenabled::text));\n"
        "    end loop;\n"
        "    execute format('alter table public.%I disable trigger user', t);\n"
        "  end loop;\n"
        f"  execute 'truncate table {tl} restart identity cascade';\n"
        "  for x in select * from jsonb_array_elements(saved) loop\n"
        "    execute format('alter table public.%I %s trigger %I', x ->> 0, case x ->> 2 when 'A' then 'enable always' when 'R' then 'enable replica' when 'D' then 'disable' else 'enable' end, x ->> 1);\n"
        "  end loop;\nend $r$;")


def table_sql(t, rows, chunk, truncate=False):
    """SQL statements (list of strings) restoring one table."""
    if not SAFE_NAME.match(t):
        raise SystemExit(f'refusing an unsafe table name: {t!r}')
    out = []
    for i in range(0, len(rows), chunk):
        js = oc.dumps_exact(rows[i:i + chunk])
        tag, o = pick_tag(js), pick_tag(js, 'rs')
        out.append(
            f"do {o} declare cols text; begin\n"
            f"  select string_agg(quote_ident(column_name), ',' order by ordinal_position) into cols from information_schema.columns where table_schema = 'public' and table_name = '{t}' and is_generated = 'NEVER';\n"
            f"  execute format('insert into public.{t} (%s) overriding system value select %s from jsonb_populate_recordset(null::public.{t}, $1) on conflict do nothing', cols, cols) using {tag}{js}{tag}::jsonb;\n"
            f"end {o};")
    out.append(
        "do $r$ declare c record; begin\n"
        f"  for c in select a.attname::text n, pg_get_serial_sequence('public.{t}', a.attname::text) s from pg_attribute a where a.attrelid = 'public.{t}'::regclass and a.attnum > 0 and not a.attisdropped loop\n"
        f"    if c.s is not null then execute format('select setval(%L, coalesce((select max(%I) from public.{t}), 1), (select count(*) > 0 from public.{t}))', c.s, c.n); end if;\n"
        "  end loop;\nend $r$;")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('folder')
    ap.add_argument('--out', default='restore.sql')
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--tables', default='')
    ap.add_argument('--truncate', action='store_true')
    ap.add_argument('--split-mb', type=float, default=4.0)
    ap.add_argument('--chunk-rows', type=int, default=300)
    a = ap.parse_args(argv)
    try:
        m = load_manifest(a.folder)
    except (OSError, ValueError) as e:
        print('cannot read manifest.json:', e, file=sys.stderr)
        return 2
    names = sorted(m['tables'])
    if a.tables:
        want = [x.strip() for x in a.tables.split(',') if x.strip()]
        unknown = [x for x in want if x not in m['tables']]
        if unknown:
            print('not in this backup:', ', '.join(unknown), file=sys.stderr)
            return 2
        names = sorted(want)
    problems = verify(a.folder, m, names)
    if problems:
        print('BACKUP IS NOT INTACT - nothing generated:\n  ' + '\n  '.join(problems), file=sys.stderr)
        return 1
    total = sum(m['tables'][t]['rows'] for t in names)
    print(f"backup made {m.get('finished_at')}: {len(names)} table(s), {total} row(s), schema {str(m.get('schema_fingerprint'))[:8]}")
    if a.dry_run:
        for t in names:
            print(f"  {t}: {m['tables'][t]['rows']}")
        print('dry run: nothing written')
        return 0
    head = HEAD.format(finished=m.get('finished_at'), mode='TRUNCATE then restore' if a.truncate else 'add missing rows only', warn=WARN_TRUNC if a.truncate else '')
    limit = int(a.split_mb * 1024 * 1024)
    files, cur, size = [], [head], len(head)
    if a.truncate:
        cur.append('-- empty every table to be restored (one statement; guards are put back afterwards)')
        cur.append(truncate_sql(names))
        size += len(cur[-1])
    for t in names:
        rows = list(read_rows(os.path.join(a.folder, m['tables'][t]['file'])))
        stmts = [f'-- table {t} ({len(rows)} rows)'] + table_sql(t, rows, max(1, a.chunk_rows), a.truncate)
        for s in stmts:
            if size + len(s) > limit and len(cur) > 1:
                files.append(cur)
                cur, size = [head], len(head)
            cur.append(s)
            size += len(s) + 1
    files.append(cur)
    base, ext = os.path.splitext(a.out)
    paths = []
    for i, parts in enumerate(files):
        p = a.out if len(files) == 1 else f'{base}.part{i + 1:02d}{ext or ".sql"}'
        with open(p, 'w', encoding='utf-8') as f:
            f.write('\n'.join(parts) + '\ncommit;\n')
        paths.append(p)
    print('written:', ', '.join(paths), '(paste in this order into the Supabase SQL editor)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
