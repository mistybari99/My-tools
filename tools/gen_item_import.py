#!/usr/bin/env python3
"""Generates supabase/phase14_import.sql from data/item_dictionary.csv (+ docs/inputs/seed_item_mapping.csv when present).
Needs supabase/phase14.sql applied first. The file has two parts the owner runs one after the other in the Supabase SQL editor:
  PART 1  preview: SELECT only, writes nothing.
  PART 2  apply: guarded by the rule item_master_apply_ok (off by default), pure INSERT ... ON CONFLICT DO NOTHING, run twice = second run skips everything.
Run from the repo root:  python3 tools/gen_item_import.py"""
import csv, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(root, 'data', 'item_dictionary.csv'), encoding='utf-8')))
mp = os.path.join(root, 'docs', 'inputs', 'seed_item_mapping.csv')
maps = list(csv.DictReader(open(mp, encoding='utf-8'))) if os.path.exists(mp) else []
BATCH = 'dict-sql-v1'
def q(s): return "'" + (s or '').replace("'", "''") + "'"
keys = ['code', 'cat_no', 'category', 'name_en', 'name_bn', 'subcategory', 'unit', 'control_class', 'note']
values = ',\n'.join('(' + ', '.join(q(r[k]) for k in keys) + ')' for r in rows)
ALIAS = 'd(code, cat_no, category, name_en, name_bn, subcategory, unit, control_class, note)'
RET = "(d.name_en ~* '^\\s*RETIRED' or d.name_bn ~* '^\\s*RETIRED' or d.note ~* '^\\s*Retired')"
out = []
out.append(f"""-- ============================================================
-- phase14_import.sql : item dictionary import ({len(rows)} rows). GENERATED by tools/gen_item_import.py - do not edit by hand.
-- Run supabase/phase14.sql first. Then:
--   PART 1  (below) = preview. It only SELECTs: nothing is written. Read the numbers.
--   PART 2  = apply. It refuses to run until the owner switches it on with this one statement (run it alone, first):
--               update public.rules set value = 'true'::jsonb where key = 'item_master_apply_ok';
--             After PART 2 has run, switch it off again:
--               update public.rules set value = 'false'::jsonb where key = 'item_master_apply_ok';
--   PART 2 is safe to run twice (a code that exists is skipped). No price or cost is imported: every new item shows "Data needed" for the price.
--   Existing items (the 57 seed items and their prices) are never touched; retired codes are created inactive and stay reserved.
-- ============================================================

-- ======================== PART 1 : PREVIEW (writes nothing) ========================
with dd(code, cat_no, category, name_en, name_bn, subcategory, unit, control_class, note) as materialized (values
{values}
), k as (
  select d.*, m.item_type, public._item_unit_code(d.unit) as unit_code, {RET} as retired, exists (select 1 from public.items i where i.code = d.code) as already
  from dd d left join public.item_class_map m on m.control_class = d.control_class and m.active
)
select metric, value from (
  select 1 as o, 'rows in file' as metric, count(*)::text as value from k
  union all select 2, 'already in items (will be skipped)', count(*)::text from k where already
  union all select 3, 'to create', count(*)::text from k where not already and item_type is not null and unit_code is not null
  union all select 4, '  of which retired (created inactive, code reserved)', count(*)::text from k where not already and item_type is not null and unit_code is not null and retired
  union all select 5, 'cannot be created (unmapped class / unknown unit)', count(*)::text from k where not already and (item_type is null or unit_code is null)
  union all select 10, 'type: ' || item_type, count(*)::text from k where not already and item_type is not null group by item_type
  union all select 20, 'category ' || cat_no || ' ' || category, count(*)::text from k where not already group by cat_no, category
) z order by o, metric;
""")
p2 = f"""
-- ======================== PART 2 : APPLY (needs the switch, see the top) ========================
begin;
do $g$ begin
  if not coalesce((select (value #>> '{{}}')::boolean from public.rules where key = 'item_master_apply_ok'), false) then
    raise exception 'Import is switched off. Run PART 1 first. To allow it: update public.rules set value = ''true''::jsonb where key = ''item_master_apply_ok''; (then run PART 2 again)';
  end if;
end $g$;
select set_config('bos.item_import', '1', true), set_config('bos.item_sys', '1', true);   -- no per-row audit lines; one audit line for the batch
insert into public.item_import_batches (batch_id, expected_rows) values ('{BATCH}', {len(rows)}) on conflict (batch_id) do nothing;

create temp table _dict on commit drop as
select * from (values
{values}
) {ALIAS};

insert into public.option_lists (list_code, value_code, label_bn, label_en, sort, extra)
  select distinct on (d.cat_no) 'item_categories', 'c' || d.cat_no, '', d.category, d.cat_no::int, jsonb_build_object('cat_no', d.cat_no, 'source', 'dictionary') from _dict d order by d.cat_no, d.code
  on conflict (list_code, value_code) do nothing;
insert into public.option_lists (list_code, value_code, label_bn, label_en, sort, extra)
  select distinct on (d.cat_no, d.subcategory) 'item_subcategories', 'c' || d.cat_no || '_' || left(md5(lower(d.subcategory)), 8), '', d.subcategory, d.cat_no::int,
         jsonb_build_object('category', 'c' || d.cat_no, 'cat_no', d.cat_no, 'source', 'dictionary') from _dict d where d.subcategory <> '' order by d.cat_no, d.subcategory, d.code
  on conflict (list_code, value_code) do nothing;

insert into public.items (code, name_bn, name_en, category, unit, sub_category, sell_price, is_active, item_type, control_class, count_in_business, sellable, tracked, source, import_batch, retired_at, retired_reason)
  select d.code, coalesce(nullif(d.name_bn, ''), d.name_en), nullif(d.name_en, ''), 'c' || d.cat_no, public._item_unit_code(d.unit),
         case when d.subcategory <> '' then 'c' || d.cat_no || '_' || left(md5(lower(d.subcategory)), 8) end, null, not {RET},
         m.item_type, d.control_class, f.o_count and not {RET}, f.o_sell, false, case m.item_type when 'finished_good' then 'made' when 'resale' then 'bought' end, '{BATCH}',
         case when {RET} then now() end, case when {RET} then left(coalesce(nullif(d.note, ''), 'Retired in the dictionary'), 200) end
  from _dict d
  join public.item_class_map m on m.control_class = d.control_class and m.active
  cross join lateral public._item_type_flags(m.item_type) f
  where public._item_unit_code(d.unit) is not null and d.code ~ '^[0-9]{{2}}-[0-9]{{3,}}$' and left(d.code, 2) = d.cat_no
  order by d.code
  on conflict (code) do nothing;
"""
if maps:
    mv = ',\n'.join('(' + ', '.join([q(r['seed_code']), q(r['best_code']), r['confidence'], r['auto']]) + ')' for r in maps)
    p2 += f"""
-- old seed items -> dictionary suggestions (only the high-confidence rows are linked; the rest wait in the "needs decision" list)
insert into public.item_mapping_review (item_id, suggested_code, confidence, auto_ok)
  select i.id, v.best_code, v.confidence, v.auto = 1
  from (values
{mv}
  ) v(seed_code, best_code, confidence, auto)
  join public.items i on i.code = v.seed_code and i.import_batch is null
  on conflict (item_id) do nothing;
select public.item_mapping_autolink() as auto_linked;
"""
p2 += f"""
update public.item_import_batches b set chunks = 1, rows_seen = {len(rows)}, created = (select count(*) from public.items where import_batch = b.batch_id),
  retired = (select count(*) from public.items where import_batch = b.batch_id and retired_at is not null), last_at = now()
  where b.batch_id = '{BATCH}';
insert into public.audit_log (action, table_name, record_id, detail)
  select 'import', 'items', '{BATCH}', jsonb_build_object('batch', '{BATCH}', 'source', 'item dictionary (SQL file)', 'expected_rows', {len(rows)})
  where not exists (select 1 from public.audit_log where action = 'import' and table_name = 'items' and record_id = '{BATCH}');
commit;

-- result: how many dictionary items exist now (expected {len(rows)} when everything was created)
select count(*) filter (where import_batch is not null) as dictionary_items, count(*) filter (where import_batch is not null and retired_at is not null) as retired_items,
       count(*) filter (where import_batch is null) as old_items from public.items;
"""
txt = out[0] + p2
open(os.path.join(root, 'supabase', 'phase14_import.sql'), 'w', encoding='utf-8').write(txt)
print('rows', len(rows), 'mapping', len(maps), 'bytes', len(txt.encode()))
