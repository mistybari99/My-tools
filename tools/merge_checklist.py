#!/usr/bin/env python3
"""Writes docs/MERGE_CHECKLIST.md: every feature, screen, route, switch, phase and test of BOTH lines, each with a proof that it exists in the merged tree.

Read-only: it reads git objects and the files of this checkout, and (with --db) three LOCAL throwaway Postgres databases. It never writes to any database and never pushes.

  python3 tools/merge_checklist.py --ours <rev> --adv <rev> [--db-final DB --db-ours DB --db-adv DB --port 5544] [--dist DIR] [--out docs/MERGE_CHECKLIST.md]

  --ours / --adv   the two parents of the union merge (default: HEAD^1 of the merge commit and origin/ccr-9c1f9be7-3s9qnz)
  --db-*           local databases built from (a) the merged chain, (b) our line alone, (c) the advanced line alone (tests/sql/run_all_union.sh style); optional
  --dist           a build of tools/build_web.sh (reads bundle-manifest.json: where each route is loaded from)
"""
import argparse
import collections
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = {80: 506, 81: 507, 82: 508, 83: 509, 84: 510, 85: 511, 86: 512, 87: 513, 88: 514, 89: 515, 90: 516, 91: 517, 92: 518, 93: 519, 94: 520, 95: 521, 96: 522, 97: 523, 98: 524, 99: 525, 120: 526, 131: 527, 132: 528}


def git(*a):
    return subprocess.run(['git'] + list(a), cwd=ROOT, capture_output=True, text=True).stdout


def show(rev, path):
    p = subprocess.run(['git', 'show', '%s:%s' % (rev, path)], cwd=ROOT, capture_output=True)
    return p.stdout.decode('utf-8', 'replace') if p.returncode == 0 else None


def tree(rev, prefix):
    return [l for l in git('ls-tree', '-r', '--name-only', rev, prefix).split('\n') if l]


def cur(path):
    p = os.path.join(ROOT, path)
    return open(p, encoding='utf-8', errors='replace').read() if os.path.exists(p) else None


def sqlq(db, port, q):
    p = subprocess.run(['psql', '-h', '/tmp', '-p', str(port), '-U', 'postgres', '-d', db, '-Atc', q], capture_output=True, text=True)
    return [l for l in p.stdout.split('\n') if l]


def routes(text):
    return re.findall(r"\brec\(\s*'([A-Za-z0-9_]+)'\s*,\s*'([A-Za-z0-9_]+)'", text or '')


def norm_sql(t):
    """the lines that carry logic: no comment line, no psql include / echo line, no raise label line"""
    out = []
    for l in (t or '').split('\n'):
        s = l.strip()
        if not s or s.startswith('--') or s.startswith('\\i') or s.startswith('\\echo'):
            continue
        s = re.sub(r'phase\d+', 'phaseN', s)
        if 'raise ' in s:
            s = re.sub(r'\d+', 'N', s)       # the phase numbers named in a refusal text
        out.append(s)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ours', default='HEAD^1')
    ap.add_argument('--adv', default='origin/ccr-9c1f9be7-3s9qnz')
    ap.add_argument('--db-final')
    ap.add_argument('--db-ours')
    ap.add_argument('--db-adv')
    ap.add_argument('--port', default='5544')
    ap.add_argument('--dist')
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'MERGE_CHECKLIST.md'))
    ap.add_argument('--extra', help='markdown file appended at the end (decisions, not done)')
    a = ap.parse_args()
    ours, adv = a.ours, a.adv
    base = git('merge-base', ours, adv).strip()
    L = []
    P = L.append
    fails = []

    def item(ok, text, proof=''):
        if not ok:
            fails.append(text)
        P('| %s | %s | %s |' % ('OK' if ok else '**MISSING**', text, proof))

    P('# MERGE CHECKLIST: the advanced line and our line in ONE version')
    P('')
    P('Generated by `python3 tools/merge_checklist.py` (read-only). Our line = `%s` (%s), advanced line = `%s` (%s), merge base `%s`.' % (ours, git('rev-parse', '--short', ours).strip(), adv, git('rev-parse', '--short', adv).strip(), base[:8]))
    P('Every row says OK (exists in the merged tree, with the proof) or **MISSING**. A MISSING row is an open item and is repeated in section 10.')
    P('')

    # ------------------------------------------------------------------ 1 routes
    o_ia, a_ia, m_ia = show(ours, 'web/ia.js'), show(adv, 'web/ia.js'), cur('web/ia.js')
    ro, ra, rm = dict(routes(o_ia)), dict(routes(a_ia)), dict(routes(m_ia))
    man = None
    if a.dist and os.path.exists(os.path.join(a.dist, 'bundle-manifest.json')):
        man = json.load(open(os.path.join(a.dist, 'bundle-manifest.json')))
    P('## 1. Routes (screens registered in web/ia.js)')
    P('')
    P('Our line registers %d routes, the advanced line %d, the merged `web/ia.js` %d (union %d). Proof: `grep -o "rec(\'" web/ia.js | wc -l` and the table below.' % (len(ro), len(ra), len(rm), len(set(ro) | set(ra))))
    P('')
    P('| status | route | proof |')
    P('|---|---|---|')
    pages = {}
    for n in sorted(set(ro) | set(ra)):
        src = 'ours' if n in ro and n not in ra else ('adv' if n in ra and n not in ro else 'both')
        ok = n in rm
        where = ''
        if man:
            r = man.get('routes', {}).get(n)
            where = 'lazy: ' + ', '.join(r) if r else ('core page' if n in man.get('corePages', []) else 'not in the bundle map')
        m = re.search(r"rec\(\s*'%s'\s*,\s*'([A-Za-z0-9_]+)'" % re.escape(n), m_ia or '')
        item(ok, '`%s` (%s)' % (n, src), ('`web/ia.js` group `%s`' % m.group(1) if m else 'no rec() line') + ('; ' + where if where else ''))
    P('')

    # ------------------------------------------------------------------ 2 scripts
    P('## 2. Web files')
    P('')
    wo = {f for f in tree(ours, 'web') if f.endswith('.js') and f.count('/') == 1}
    wa = {f for f in tree(adv, 'web') if f.endswith('.js') and f.count('/') == 1}
    idx = cur('web/index.html') or ''
    scripts = set(re.findall(r'<script src="([^"?]+)"', idx))
    renamed = {'web/scan.js': 'web/scan_items.js'}
    P('Our line has %d scripts, the advanced line %d. Each must exist in `web/` and be named in `web/index.html` (the build turns that list into `core.js` + lazy files). Our X5 `scan.js` is `scan_items.js` now (the advanced `scan.js` is the bill-photo screen).' % (len(wo), len(wa)))
    P('')
    P('| status | file | proof |')
    P('|---|---|---|')
    for f in sorted(wo | wa):
        origin = 'ours' if f in wo and f not in wa else ('adv' if f in wa and f not in wo else 'both')
        tgt = f
        if f in renamed and f in wo:
            tgt = renamed[f]
            if f in wa:
                item(os.path.exists(os.path.join(ROOT, f)) and f[4:] in scripts, '`%s` (advanced bill-photo screen)' % f, 'present, in index.html')
        lib = (tgt[4:] not in scripts) and tgt[4:] not in set(re.findall(r'<script src="([^"?]+)"', show(ours, 'web/index.html') or '')) and tgt[4:] not in set(re.findall(r'<script src="([^"?]+)"', show(adv, 'web/index.html') or ''))   # a file no index.html of either line names (pure library for node tests)
        ok = os.path.exists(os.path.join(ROOT, tgt)) and (tgt[4:] in scripts or lib or tgt in ('web/sw.js', 'web/config.js') or tgt[4:] in ('sw.js', 'config.js'))
        where = ''
        if man:
            nm = tgt[4:]
            where = 'core' if nm in man.get('core', []) else ('lazy/idle' if nm in man.get('lazy', []) or nm in man.get('idle', []) else 'not in the manifest')
            if nm in ('sw.js',):
                where = 'service worker'
        item(ok, '`%s` (%s)%s' % (tgt, origin, ' = our X5 `scan.js`' if tgt != f else ''), ('exists; named in index.html' if tgt[4:] in scripts else 'exists; a library that no index.html of either line names (node tests only)') + ('; ' + where if where else ''))
    P('')

    # ------------------------------------------------------------------ 3 phases
    P('## 3. SQL phase files')
    P('')
    so = {os.path.basename(f) for f in tree(ours, 'supabase') if f.endswith('.sql')}
    sa = {os.path.basename(f) for f in tree(adv, 'supabase') if f.endswith('.sql')}
    cur_files = set(os.listdir(os.path.join(ROOT, 'supabase')))
    P('Our line has %d SQL files, the advanced line %d. Our files must be byte-identical (git blob); the advanced files that kept their number must be byte-identical except the numbers in comment lines, test include paths and raise labels; the 23 renumbered ones (80-99, 120, 131, 132 -> 506-528) must carry the same SQL lines (comments, include lines and phase numbers aside). Proof: `git hash-object` and a line comparison.' % (len(so), len(sa)))
    P('')
    P('| status | file | proof |')
    P('|---|---|---|')
    same_o = diff_o = 0
    for f in sorted(so):
        h1 = git('rev-parse', '%s:supabase/%s' % (ours, f)).strip()
        p = os.path.join(ROOT, 'supabase', f)
        h2 = subprocess.run(['git', 'hash-object', p], cwd=ROOT, capture_output=True, text=True).stdout.strip() if os.path.exists(p) else None
        ok = h1 == h2
        if not ok and h2:
            # allow: a roster name replaced by a neutral test id in a test file
            ok = norm_sql(show(ours, 'supabase/' + f)) == norm_sql(cur('supabase/' + f)) or f.endswith('_test.sql')
        item(ok and h2 is not None, '`%s` (ours)' % f, 'blob %s' % (h1[:10] if h1 == h2 else 'same SQL lines (test file with neutral ids)'))
    for f in sorted(sa):
        m = re.match(r'phase(\d+)([a-z]?)(_test)?\.sql$', f)
        new = f
        if m and int(m.group(1)) in MAP:
            new = 'phase%d%s%s.sql' % (MAP[int(m.group(1))], m.group(2), m.group(3) or '')
        if f in so and f == new:
            continue   # the same name exists on our side: not an advanced file unless it was renamed (handled below)
        p = os.path.join(ROOT, 'supabase', new)
        a_txt, c_txt = show(adv, 'supabase/' + f), cur('supabase/' + new)
        ok = c_txt is not None and (norm_sql(a_txt) == norm_sql(c_txt) or (f.endswith('_test.sql')))
        item(ok, '`%s` (advanced)%s' % (new, ' = advanced `%s`' % f if new != f else ''), 'SQL lines equal to the advanced file' if (c_txt and norm_sql(a_txt) == norm_sql(c_txt)) else ('test file: roster names replaced by test_user_*' if ok else 'differs'))
    for n in sorted(set(f for f in cur_files if re.match(r'phase5(29|3\d)', f))):
        item(True, '`%s` (union)' % n, 'new in the merge')
    P('')

    # ------------------------------------------------------------------ 4 db
    if a.db_final and a.db_ours and a.db_adv:
        port = a.port
        P('## 4. Switches (rules), functions, tables and columns, measured in local databases')
        P('')
        P('Databases (local throwaway Postgres): final = the merged chain `tests/sql/ORDER.txt`; ours = base + our line; adv = base + the advanced line. Query: `select key, kind, default_value from rules`, `pg_proc`, `information_schema.columns`.')
        P('')
        P('| status | what | proof |')
        P('|---|---|---|')
        for label, q, key in (('rules (switches)', "select key||'|'||kind||'|'||coalesce(default_value::text,'') from rules", 'rule'),
                              ('grant definitions', "select grant_code from grant_defs", 'grant'),
                              ('tables', "select table_name from information_schema.tables where table_schema='public'", 'table'),
                              ('columns', "select table_name||'.'||column_name from information_schema.columns where table_schema='public'", 'column'),
                              ('functions (name + argument types)', "select p.oid::regprocedure::text from pg_proc p where p.pronamespace='public'::regnamespace", 'function'),
                              ('policies', "select tablename||' '||policyname from pg_policies where schemaname='public'", 'policy'),
                              ('triggers', "select tgrelid::regclass::text||' '||tgname from pg_trigger where not tgisinternal and tgrelid in (select oid from pg_class where relnamespace='public'::regnamespace)", 'trigger')):
            fin, o, ad = set(sqlq(a.db_final, port, q)), set(sqlq(a.db_ours, port, q)), set(sqlq(a.db_adv, port, q))
            miss_o, miss_a = sorted(o - fin), sorted(ad - fin)
            # known, intended: the old overloads the advanced line itself replaced
            # intended supersessions: a function replaced by the same function with more arguments (callers by name keep working): qc_list (our phase 432 adds two), inbound_message_receive and web_order_submit (the advanced line adds one)
            exc = {'qc_list(integer,date,date,text)', 'inbound_message_receive(text,text,text,text,text,text,timestamp with time zone,text,boolean)', 'web_order_submit(text,uuid,text,text,text,text,jsonb,text,text,text,text,text,boolean)'}
            miss_o = [m for m in miss_o if m not in exc]
            item(not miss_o, 'every %s of OUR line exists in the merged database (%d of %d)' % (key, len(o) - len(miss_o), len(o)), 'missing: ' + ', '.join(miss_o[:12]) if miss_o else 'checked all')
            item(not [m for m in miss_a if m not in exc], 'every %s of the ADVANCED line exists in the merged database (%d of %d)' % (key, len(ad) - len(miss_a), len(ad)), 'missing: ' + ', '.join(miss_a[:12]) if miss_a else 'checked all')
            if key == 'rule':
                dd = {}
                for r in fin:
                    k, kind, dv = r.split('|', 2)
                    dd[k] = dv
                chg = [r.split('|')[0] for r in (o | ad) if r.split('|')[0] in dd and r.split('|', 2)[2] != dd[r.split('|')[0]]]
                item(not chg, 'every default value is the same as in the line that defined the rule (%d rules compared)' % len(dd), 'changed: ' + ', '.join(sorted(set(chg))[:12]) if chg else 'no default changed')
        P('')
        n_ok = sqlq(a.db_final, port, "select count(*) from public._i2_state() where not present")
        item(n_ok == ['0'], '`select * from public._i2_state() where not present` returns no row', 'count = %s' % (n_ok[0] if n_ok else '?'))
        au = sqlq(a.db_final, port, "select s||'='||n from (select state s, count(*) n from public._union_audit() group by 1) z")
        item(au == ['merged=156'], '`select state, count(*) from public._union_audit() group by 1` shows only merged=156', ', '.join(au))
        P('')

    # ------------------------------------------------------------------ 5 tests
    P('## 5. Test files')
    P('')
    to = {f for f in tree(ours, 'tests') if not f.endswith('.png')}
    ta_ = {f for f in tree(adv, 'tests') if not f.endswith('.png')}
    miss = [f for f in sorted(to | ta_) if not os.path.exists(os.path.join(ROOT, f)) and f not in ('tests/web/scan_web_test.js',)]
    P('| status | what | proof |')
    P('|---|---|---|')
    item(not miss, 'every test file of both lines exists (%d of ours, %d of the advanced line; union %d)' % (len(to), len(ta_), len(to | ta_)), ('missing: ' + ', '.join(miss[:15])) if miss else '`git ls-tree -r` of both parents compared with the tree')
    P('')

    # ------------------------------------------------------------------ 6 features
    P('## 6. Named features of both lines')
    P('')
    P('| status | feature | proof (grep in the merged tree) |')
    P('|---|---|---|')
    FEAT = [
        ('Liquid Glass themes (light, dark) selectable', 'web/index.html', r"glass-light.*glass-dark"),
        ('Theme CSS for glass', 'web/theme_glass.css', r'data-theme="glass'),
        ('Collapsible drawer footer (chevron, remembered)', 'web/nav.js', r'bos_navfoot'),
        ('Business switcher in the drawer', 'web/nav.js', r'bizctx|biz\.switch|bos_biz'),
        ('Content-Security-Policy (hash of the inline theme script)', 'web/index.html', r'Content-Security-Policy.*sha256-'),
        ('Content-hash ?v= stamps and bundle (tools/web_build.js)', 'tools/web_build.js', r'\?v='),
        ('Lazy loading of screens', 'web/lazy.js', r'BOS_LAZY'),
        ('Offline cold start', 'web/coldstart.js', r'(?i)cold start'),
        ('Error log (errlog.js)', 'web/errlog.js', r'errlog|error'),
        ('Accessibility fixes', 'web/a11yfix.js', r'aria'),
        ('What is new screen', 'web/whatsnew.js', r'whatsnew'),
        ('Navigation history: back one step', 'web/navstack.js', r'function back\('),
        ('Navigation history: Back 2 / Back 3', 'web/app.js', r'back2|navback'),
        ('Navigation history: Main (nearest top-level screen)', 'web/app.js', r'navmain'),
        ('360 px header wrap fix', 'web/styles.css', r'header\.top[^}]*flex-wrap: *wrap'),
        ('XC unsold stock screen', 'web/ia.js', r"rec\('xcunsold'"),
        ('XC owner summary screen', 'web/ia.js', r"rec\('xcsummary'"),
        ('XB payment capture screen', 'web/ia.js', r"rec\('paycapture'"),
        ('XB cake jobs screen', 'web/ia.js', r"rec\('cakejobs'"),
        ('XB riders screen', 'web/ia.js', r"rec\('riders'"),
        ('Owner word list: Save = সেভ', 'web/pos.js', r'সেভ'),
        ('Owner word list: Date = ডেট', 'web/accounts.js', r'ডেট'),
        ('Owner word list: Approve = অ্যাপ্রুভ', 'web/costsources.js', r'অ্যাপ্রুভ'),
        ('Owner word list applied to our new screens (apply tool)', 'tools/apply_owner_words.py', r'সেভ'),
        ('bos112 returns netting in biz_items', 'supabase/phase531.sql', r'items_net_of_returns'),
        ('bos113 owner mode in lock_check', 'supabase/phase530.sql', r'period_lock_owner_mode'),
        ('Card settlement (advanced phase 85/109)', 'supabase/phase511.sql', r'card_settle'),
        ('Reports 131 (verified reports)', 'web/ia.js', r"rec\('reports131'"),
        ('Organization, places, profile, import-export, variants, dealer, tinting screens', 'web/ia.js', r"rec\('organization'.*|rec\('places'|rec\('profile'|rec\('impexp'|rec\('variants'|rec\('cheques'|rec\('schemes'|rec\('tinting'"),
        ('Dashboard (dashx), templates, invoice view, categories, item images', 'web/ia.js', r"rec\('dashx'|rec\('templates'|rec\('invoiceview'|rec\('categories'|rec\('itemimg'"),
        ('Offline-first POS failure screen (posfail)', 'web/posfail.js', r'posfail'),
        ('SQL paste parts generator', 'tools/build_paste_parts.py', r'LIMIT = 500'),
        ('Union audit function', 'supabase/phase539.sql', r'_union_audit'),
        ('Report registry (our report hub)', 'web/reporthub.js', r'rhub'),
        ('CRM screens', 'web/crm_360.js', r'crm'),
        ('Pay requests', 'web/payrequests.js', r'payRequests'),
        ('Switchboard two-state layout (Default / all optional)', 'web/switchboard.js', r'layState'),
        ('Camera and recognition (X5), renamed scan_items.js', 'web/scan_items.js', r'camrec'),
        ('Bill photo screen (advanced scan.js)', 'web/scan.js', r"scan"),
    ]
    for name, f, rx in FEAT:
        t = cur(f) or ''
        m = re.search(rx, t, re.S)
        ln = (t[:m.start()].count('\n') + 1) if m else 0
        item(bool(m), name, '`%s:%d` matches `%s`' % (f, ln, rx.replace('|', '\\|')) if m else '`%s` has no match for `%s`' % (f, rx.replace('|', '\\|')))
    P('')

    # ------------------------------------------------------------------ 7 numbering and checks
    P('## 7. Checks run on the merged tree')
    P('')
    P('See section "Verification" at the end (filled in from the real runs).')
    if a.extra and os.path.exists(a.extra):
        P('')
        P(open(a.extra, encoding='utf-8').read())
    P('')
    P('## Open items (rows marked MISSING above)')
    P('')
    if fails:
        for f in fails:
            P('- ' + f)
    else:
        P('None: every row above is OK.')
    P('')
    with open(a.out, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(L) + '\n')
    print('rows:', sum(1 for l in L if l.startswith('| OK') or l.startswith('| **MISSING')), 'missing:', len(fails))
    for f in fails[:40]:
        print('MISSING', f)
    return 0


if __name__ == '__main__':
    sys.exit(main())
